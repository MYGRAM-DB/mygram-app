-- Additive localization foundation for MYGRAM beta.
-- No existing user data, tables, or policies are dropped.
create table if not exists public.translation_catalog (
  id bigint generated by default as identity primary key,
  source_locale text not null default 'en',
  target_locale text not null references public.supported_locales(code),
  message_key text not null,
  source_text text not null,
  translated_text text not null,
  status text not null default 'pending' check (status in ('pending','machine_draft','reviewed','approved','rejected')),
  provider text not null default 'human' check (provider in ('human','ai','import')),
  model_name text,
  source_hash text,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (target_locale, message_key, source_hash)
);
create index if not exists translation_catalog_lookup_idx on public.translation_catalog(target_locale, message_key, status);
alter table public.translation_catalog enable row level security;
revoke all on public.translation_catalog from public;
grant select on public.translation_catalog to anon, authenticated;
drop policy if exists translation_catalog_read_approved on public.translation_catalog;
create policy translation_catalog_read_approved on public.translation_catalog
  for select to anon, authenticated using (status = 'approved');
-- Writes are intentionally reserved to service_role / controlled server functions.
revoke insert, update, delete on public.translation_catalog from anon, authenticated;

create table if not exists public.translation_cache (
  cache_key text primary key,
  source_locale text not null,
  target_locale text not null references public.supported_locales(code),
  source_text text not null,
  translated_text text not null,
  provider text not null default 'ai',
  model_name text,
  created_at timestamptz not null default now(),
  expires_at timestamptz
);
create index if not exists translation_cache_expiry_idx on public.translation_cache(expires_at);
alter table public.translation_cache enable row level security;
revoke all on public.translation_cache from public;
-- Cache may contain user-provided text; no direct client reads or writes.
revoke all on public.translation_cache from anon, authenticated;

alter table public.user_preferences
  add column if not exists auto_detect_language boolean not null default true,
  add column if not exists auto_detect_region boolean not null default true,
  add column if not exists timezone_name text,
  add column if not exists country_detection_source text check (country_detection_source is null or country_detection_source in ('manual','browser_locale','ip_approximate','gps_consent')),
  add column if not exists language_detection_source text check (language_detection_source is null or language_detection_source in ('manual','browser_locale','account_default')),
  add column if not exists location_consent_at timestamptz,
  add column if not exists updated_by uuid generated always as (user_id) stored;
-- Existing user_preferences policies are preserved; enforce ownership at row level.
alter table public.user_preferences enable row level security;
drop policy if exists user_preferences_select_own on public.user_preferences;
create policy user_preferences_select_own on public.user_preferences
  for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists user_preferences_insert_own on public.user_preferences;
create policy user_preferences_insert_own on public.user_preferences
  for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists user_preferences_update_own on public.user_preferences;
create policy user_preferences_update_own on public.user_preferences
  for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
drop policy if exists user_preferences_delete_own on public.user_preferences;
create policy user_preferences_delete_own on public.user_preferences
  for delete to authenticated using (user_id = (select auth.uid()));

comment on table public.translation_catalog is 'Reviewed UI translation catalog; only approved strings are visible to app clients.';
comment on table public.translation_cache is 'Private AI translation cache for dynamic text; service functions only.';
comment on column public.user_preferences.auto_detect_region is 'Uses approximate region by default; precise GPS requires explicit consent.';
