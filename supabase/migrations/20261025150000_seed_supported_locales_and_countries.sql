-- Canonical beta registries synchronized from the app's current language and country pickers.
-- Country display names remain localized by country-data.js / Intl.DisplayNames.
create table if not exists public.supported_locales (
  code text primary key check (code ~ '^[a-z]{2,3}(-[A-Z]{2})?$'),
  native_name text not null check (char_length(btrim(native_name)) between 1 and 80),
  is_rtl boolean not null default false,
  enabled boolean not null default true,
  updated_at timestamptz not null default now()
);
create table if not exists public.supported_countries (
  code text primary key check (code ~ '^[A-Z]{2}$'),
  calling_code text,
  national_prefix text not null default '',
  enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint supported_countries_calling_code_format check (calling_code is null or calling_code ~ '^\\+[0-9]{1,4}$')
);
create index if not exists supported_countries_calling_code_idx on public.supported_countries(calling_code);
alter table public.supported_locales enable row level security;
alter table public.supported_countries enable row level security;
revoke all on public.supported_locales from public;
revoke all on public.supported_countries from public;
grant select on public.supported_locales to anon, authenticated;
grant select on public.supported_countries to anon, authenticated;
drop policy if exists supported_locales_read_enabled on public.supported_locales;
create policy supported_locales_read_enabled on public.supported_locales
for select to anon, authenticated using (enabled = true);
drop policy if exists supported_countries_read_enabled on public.supported_countries;
create policy supported_countries_read_enabled on public.supported_countries
for select to anon, authenticated using (enabled = true);
